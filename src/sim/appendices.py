"""Paste-ready thesis appendices A-D (T-22).

The files in ``docs/appendices/`` are assembled from the canonical FSM, agent
prompts, judge rubrics and T-21 exemplars. Page caps are a character proxy, not
an estimate of rendered ABNT pages.
"""

from __future__ import annotations

import re
from pathlib import Path

from sim.fsm import DEFAULT_FSM_DIR, FsmSpec, load_fsm
from sim.io import atomic_write
from sim.prompts import DEFAULT_PROMPTS_DIR, load_prompt

CHARS_PER_PAGE = 3000
PAGE_BUDGETS = {"a": 0.5, "b": 1.5, "c": 1.0, "d": 2.0}
BASELINE_HEADING = "# How to handle a request"
FSM_PLACEHOLDERS = ("$knowledge_base", "$user_data_fields", "$shared")
CLAIMS_HEADING = "# Claims"
GLOBAL_HEADINGS = (
    "# Accuracy",
    "# Relevance",
    "# Task completed",
    "# Offensive content",
)
DEFAULT_CASES_PATH = Path("results/cases.md")
PAIR_HEADINGS = (
    ("helped", "## FSM helped: `adversarial_08`"),
    ("restricted", "## FSM restricted: `edge_05`"),
    ("tie", "## Tie: `happy_path_07`"),
)
BASELINE_SUBHEADING = "### Baseline (`"
FSM_SUBHEADING = "### FSM (`"
TRANSCRIPT_FENCE = "```text"
ELLIPSIS = "[...]"


class AppendicesError(RuntimeError):
    """T-22 cannot assemble an appendix; the message says what to fix."""


def page_chars(text: str) -> int:
    """Return the character count of emitted Markdown, including fences."""
    return len(text)


def char_budget(letter: str) -> int:
    """Return the character cap for appendix ``letter``."""
    return int(PAGE_BUDGETS[letter] * CHARS_PER_PAGE)


def check_budget(letter: str, text: str) -> None:
    """Refuse an appendix whose Markdown exceeds its character cap."""
    n = page_chars(text)
    cap = char_budget(letter)
    if n > cap:
        raise AppendicesError(
            f"appendix {letter} is {n} characters, over the cap of {cap}"
        )


def write_appendices(
    out_dir: Path,
    *,
    fsm_dir: Path = DEFAULT_FSM_DIR,
    prompts_dir: Path = DEFAULT_PROMPTS_DIR,
    cases_path: Path = DEFAULT_CASES_PATH,
) -> None:
    """Write ``a.md``-``d.md`` under ``out_dir``."""
    spec = load_fsm(fsm_dir)
    bodies = {
        "a": _render_a(spec),
        "b": _render_b(spec, prompts_dir),
        "c": _render_c(prompts_dir),
        "d": _render_d(cases_path),
    }
    for letter, text in bodies.items():
        check_budget(letter, text)
        atomic_write(out_dir / f"{letter}.md", text)


def _render_a(spec: FsmSpec) -> str:
    """Return appendix A: mermaid generated from the loaded FSM spec."""
    return (
        "Paste as: Apêndice A — Diagrama da máquina de estados\n"
        "\n"
        "Source: `data/fsm/machine.yaml`, generated by `just fsm-diagram`.\n"
        "\n"
        f"```mermaid\n{spec.to_mermaid()}\n```\n"
    )


def _render_b(spec: FsmSpec, prompts_dir: Path) -> str:
    """Return appendix B: both agent templates, placeholders unfilled."""
    procedure = _markdown_section(
        load_prompt("baseline", directory=prompts_dir).template, BASELINE_HEADING
    )
    fsm = load_prompt("fsm_template", directory=prompts_dir)
    _require_markers(fsm.template, FSM_PLACEHOLDERS, "fsm_template.md")
    shared = load_prompt("agent_shared", directory=prompts_dir)
    packages = "\n".join(
        f"- `{Path(state.package).name}`" for state in spec.states.values()
    )
    return (
        "Paste as: Apêndice B — Prompts dos dois agentes\n"
        "\n"
        f"Both agents include `$shared` from `agent_shared.md` "
        f"(version {shared.version}). That block is not reprinted here.\n"
        "\n"
        "The knowledge base is the same for both agents and is omitted. "
        "Placeholders `$knowledge_base` and `$user_data_fields` are left unfilled.\n"
        "\n"
        "## Baseline\n"
        "\n"
        f"```text\n{procedure}\n```\n"
        "\n"
        "## FSM template\n"
        "\n"
        f"```text\n{fsm.template}\n```\n"
        "\n"
        "## State packages\n"
        "\n"
        f"{packages}\n"
    )


def _render_c(prompts_dir: Path) -> str:
    """Return appendix C: blindness block and selected rubric sections."""
    shared = load_prompt("judge_shared", directory=prompts_dir)
    facts = load_prompt("judge_facts", directory=prompts_dir)
    glob = load_prompt("judge_global", directory=prompts_dir)
    claims = _markdown_section(facts.template, CLAIMS_HEADING)
    global_sections = "\n\n".join(
        _markdown_section(glob.template, heading) for heading in GLOBAL_HEADINGS
    )
    body = (
        "Paste as: Apêndice C — Rubricas do juiz\n"
        "\n"
        "Blindness block from `judge_shared.md`. The JSON Schema that constrains "
        "the two judge calls is omitted; pydantic is the source.\n"
        "\n"
        f"{shared.template}\n"
        "\n"
        "Claims are labelled `supported_by_kb`.\n"
        "\n"
        f"{claims}\n"
        "\n"
        "Global fields: `accuracy`, `relevance`, `task_completed`, "
        "`offensive_content`.\n"
        "\n"
        f"{global_sections}\n"
    )
    if "# Output schema" in body:
        raise AppendicesError("appendix C leaked # Output schema")
    return body


def _require_markers(text: str, markers: tuple[str, ...], source: str) -> None:
    """Raise unless every marker appears in ``text``."""
    missing = [marker for marker in markers if marker not in text]
    if missing:
        raise AppendicesError(
            f"{source} is missing {missing}: the extractor refuses to guess"
        )


def _markdown_section(text: str, heading: str) -> str:
    """Return the section that starts at ``heading``, or raise if it is absent."""
    match = re.search("^" + re.escape(heading) + r"(?:\n|$)", text, flags=re.MULTILINE)
    if match is None:
        raise AppendicesError(
            f"expected heading {heading!r} is missing: the extractor refuses "
            f"to guess the section"
        )
    hashes = heading.split(" ", 1)[0]
    nxt = re.search(rf"^#{{1,{len(hashes)}}} ", text[match.end() :], flags=re.MULTILINE)
    end = match.end() + nxt.start() if nxt else len(text)
    return text[match.start() : end].strip()


def _render_d(cases_path: Path) -> str:
    """Return appendix D: the three T-21 rank-1 pairs from ``cases.md``."""
    source = cases_path.read_text(encoding="utf-8")
    pairs: list[str] = []
    helped_fsm = ""
    for key, heading in PAIR_HEADINGS:
        body = _h2_block(source, heading)
        baseline_head = _line_starting(body, BASELINE_SUBHEADING)
        fsm_head = _line_starting(body, FSM_SUBHEADING)
        baseline = _transcript_after(body, BASELINE_SUBHEADING)
        fsm = _transcript_after(body, FSM_SUBHEADING)
        if key == "helped":
            helped_fsm = fsm
        pairs.append(
            f"{heading}\n"
            f"\n"
            f"{baseline_head}\n"
            f"\n"
            f"{TRANSCRIPT_FENCE}\n{baseline}\n```\n"
            f"\n"
            f"{fsm_head}\n"
            f"\n"
            f"{TRANSCRIPT_FENCE}\n{fsm}\n```\n"
        )
    text = (
        "Paste as: Apêndice D — Diálogos exemplares\n"
        "\n"
        "T-21 rank-1 pairs from `results/cases.md`. Comments stay there.\n"
        "\n" + "\n".join(pairs)
    )
    if page_chars(text) <= char_budget("d"):
        return text
    if not helped_fsm:
        raise AppendicesError("helped FSM transcript is empty; cannot truncate")
    lines = helped_fsm.splitlines()
    truncated = f"{lines[0]}\n{ELLIPSIS}\n{lines[-1]}"
    squeezed = text.replace(helped_fsm, truncated, 1)
    if squeezed == text:
        raise AppendicesError("could not locate the helped FSM transcript to truncate")
    return squeezed


def _h2_block(text: str, heading: str) -> str:
    """Return the `##` section that starts with ``heading``."""
    start = text.find(heading)
    if start == -1:
        raise AppendicesError(
            f"cases.md is missing {heading!r}: the extractor refuses to guess"
        )
    line_end = text.find("\n", start)
    if line_end == -1:
        return text[start:]
    rest = text[line_end + 1 :]
    nxt = re.search(r"^## ", rest, flags=re.MULTILINE)
    if nxt is None:
        return text[start:]
    return text[start : line_end + 1 + nxt.start()]


def _line_starting(body: str, prefix: str) -> str:
    """Return the full line that starts with ``prefix``."""
    start = body.find(prefix)
    if start == -1:
        raise AppendicesError(
            f"cases.md is missing {prefix!r}: the extractor refuses to guess"
        )
    end = body.find("\n", start)
    return body[start:] if end == -1 else body[start:end]


def _transcript_after(body: str, subheading: str) -> str:
    """Return the fenced transcript that follows ``subheading``."""
    start = body.find(subheading)
    if start == -1:
        raise AppendicesError(
            f"cases.md is missing {subheading!r}: the extractor refuses to guess"
        )
    region = body[start:]
    fence = region.find(TRANSCRIPT_FENCE)
    if fence == -1:
        raise AppendicesError(
            f"cases.md is missing a {TRANSCRIPT_FENCE} fence after {subheading!r}"
        )
    inner = fence + len(TRANSCRIPT_FENCE)
    if inner < len(region) and region[inner] == "\n":
        inner += 1
    close = region.find("```", inner)
    if close == -1:
        raise AppendicesError(
            f"cases.md has an unclosed {TRANSCRIPT_FENCE} fence after {subheading!r}"
        )
    return region[inner:close].strip("\n")
